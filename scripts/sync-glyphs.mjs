// Copies the SF Symbols this app uses out of a GlyphStudio checkout into a small TypeScript table.
// Usage: node scripts/sync-glyphs.mjs <path to GlyphStudio> <manifest.json> <output.ts>
// The manifest maps an app icon key to an Apple symbol name, for example { "search": "magnifyingglass" }.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [glyphStudio, manifestPath, outputPath] = process.argv.slice(2);
if (!glyphStudio || !manifestPath || !outputPath) {
  console.error('Usage: node scripts/sync-glyphs.mjs <GlyphStudio> <manifest.json> <output.ts>');
  process.exit(1);
}

const symbolDir = join(glyphStudio, 'sfsymbols/src/commonMain/kotlin/com/composables/sfsymbols/monochrome');
const pascal = (name) => 'SF' + name.split('.').map((part) => part[0].toUpperCase() + part.slice(1)).join('');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

const lines = Object.entries(manifest).map(([key, appleName]) => {
  const file = join(symbolDir, `${pascal(appleName)}.kt`);
  let source;
  try {
    source = readFileSync(file, 'utf8');
  } catch {
    throw new Error(`GlyphStudio has no symbol "${appleName}" (looked for ${file})`);
  }
  const width = source.match(/viewportWidth = ([\d.]+)f/)[1];
  const height = source.match(/viewportHeight = ([\d.]+)f/)[1];
  const paths = [...source.matchAll(/addSfPath\("([^"]+)"/g)].map((match) => match[1]);
  return `  ${JSON.stringify(key)}: [${width}, ${height}, ${paths.map((d) => JSON.stringify(d)).join(', ')}],`;
});

writeFileSync(
  outputPath,
  `// Generated by scripts/sync-glyphs.mjs from GlyphStudio (SF Symbols). Do not edit by hand.\n` +
    `// Each entry is [viewBox width, viewBox height, ...path data].\n` +
    `export const glyphs = {\n${lines.join('\n')}\n} as const;\n`,
);
console.log(`Wrote ${lines.length} glyphs to ${outputPath}`);
